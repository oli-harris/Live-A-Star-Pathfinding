import pygame
import A_Star
from time import time
from PIL import Image

BACKGROUND = (235, 235, 235)
FOREGROUND = (0, 0, 0)

WALL = (100, 100, 100)
START = (0, 255, 0)
END = (255, 0, 0)
PATHCOLOUR = (50, 50, 235)

Image.new('RGB', (16, 16), WALL).save("img\wall.png")
WALL_ICON = pygame.image.load("img\wall.png")

Image.new('RGB', (16, 16), START).save("img\start.png")
START_ICON = pygame.image.load("img\start.png")

Image.new('RGB', (16, 16), END).save("img\end.png")
END_ICON = pygame.image.load("img\end.png")

Image.new('RGB', (16, 16), BACKGROUND).save("img\erase.png")
ERASE_ICON = pygame.image.load("img\erase.png")


class RunWindow():
    """Creates a window with a grid."""

    def __init__(self, gridSizeX, gridSizeY, displayHeight):
        displayWidth = (displayHeight/gridSizeY)*gridSizeX

        self.heightByGridSizeY = int(displayHeight/gridSizeY)
        self.widthByGridSizeX = int(displayWidth/gridSizeX)

        self.displayHeight = self.heightByGridSizeY*gridSizeY
        self.displayWidth = self.widthByGridSizeX*gridSizeX

        self.display = pygame.display.set_mode(
            (int(self.displayWidth), int(self.displayHeight)))

        self.gridSizeX = gridSizeX
        self.gridSizeY = gridSizeY
        self.maze = [[0 for x in range(self.gridSizeX)]
                     for y in range(self.gridSizeY)]

        self.click = False
        self.erase = False
        self.selection = 1

        pygame.init()
        self.drawGrid()
        self.CLOCK = pygame.time.Clock()
        pygame.display.set_caption('Live A* Path Finding')
        pygame.display.set_icon(WALL_ICON)
        self.main()

    def drawGrid(self):
        """Draws the grid"""
        self.display.fill(BACKGROUND)
        for x in range(self.gridSizeX):
            for y in range(self.gridSizeY):
                rect = pygame.Rect(
                    (x*self.widthByGridSizeX), (y*self.heightByGridSizeY), self.widthByGridSizeX, self.heightByGridSizeY)

                if self.maze[y][x] == 1:
                    self.display.fill(WALL, rect)
                elif self.maze[y][x] == 2:
                    self.display.fill(START, rect)
                elif self.maze[y][x] == 3:
                    self.display.fill(END, rect)
                elif self.maze[y][x] == 4:
                    self.display.fill(PATHCOLOUR, rect)

                pygame.draw.rect(self.display, FOREGROUND, rect, 1)
        pygame.display.update()

    def getAStar(self):
        """Adds the path generated by A*"""
        # Removes old solution
        self.maze = [[x if x != 4 else 0 for x in y] for y in self.maze]

        # Makes sure there is a start and end node
        if (any(2 in _ for _ in self.maze) and any(3 in _ for _ in self.maze)):
            time1 = time()

            try:
                solution = A_Star.AStar(self.maze, self.gridSizeX,
                                        self.gridSizeY).calc()
            except:
                pygame.display.set_caption('Unsolvable!')
                return

            pygame.display.set_caption(
                f'Done after {round(time()-time1,4)} seconds')

            for i, j in solution[1:-1]:
                self.maze[i][j] = 4
            self.drawGrid()
        else:
            pygame.display.set_caption('No Start or End Node')

    def updateMazeByMousePos(self, value, x, y):
        self.maze[int(y/self.heightByGridSizeY)
                  ][int(x/self.widthByGridSizeX)] = value
        self.getAStar()
        self.drawGrid()

    def checkInput(self):
        """Checks all inputs"""
        for event in pygame.event.get():
            # on press exit
            if event.type == pygame.QUIT:
                pygame.quit()
                exit()

            # on click
            elif event.type == pygame.MOUSEBUTTONDOWN:
                if event.button == 1:
                    self.click = True
                    self.erase = False
                elif event.button == 3:
                    self.click = True
                    self.erase = True

            # on stop clicking
            elif event.type == pygame.MOUSEBUTTONUP:
                if self.erase:
                    switch = {1: WALL_ICON, 2: START_ICON, 3: END_ICON}
                    pygame.display.set_icon(switch.get(self.selection))

                self.click = False

            # on keypress
            elif event.type == pygame.KEYDOWN:
                if event.key == pygame.K_1:
                    self.selection = 1
                    pygame.display.set_icon(WALL_ICON)
                elif event.key == pygame.K_2:
                    self.selection = 2
                    pygame.display.set_icon(START_ICON)
                elif event.key == pygame.K_3:
                    self.selection = 3
                    pygame.display.set_icon(END_ICON)
                elif event.key == pygame.K_ESCAPE:
                    self.maze = [[0 for _ in range(self.gridSizeX)]
                                 for _ in range(self.gridSizeY)]
                    self.drawGrid()

        if self.click:
            x, y = pygame.mouse.get_pos()
            currentMazePos = self.maze[int(y/self.heightByGridSizeY)
                                       ][int(x/self.widthByGridSizeX)]
            if self.erase:
                pygame.display.set_icon(ERASE_ICON)
                if 0 < currentMazePos < 4:
                    self.updateMazeByMousePos(0, x, y)
            elif self.selection == 1 and currentMazePos != 1:
                self.updateMazeByMousePos(1, x, y)
            elif self.selection == 2 and not any(2 in _ for _ in self.maze):
                self.updateMazeByMousePos(2, x, y)
            elif self.selection == 3 and not any(3 in _ for _ in self.maze):
                self.updateMazeByMousePos(3, x, y)

    def main(self):
        while True:
            self.checkInput()
            self.CLOCK.tick(60)


window = RunWindow(25, 25, 1000)
